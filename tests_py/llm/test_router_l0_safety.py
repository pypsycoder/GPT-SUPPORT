# --------------------------------------------------------------------------- #
# breathing + хроничность: многодневный/нагрузочный фон у СН/ХБП-пациента —
# concern, а не urgent. Найдено на patient-sim (s07_comorbid_dose): "ноги
# опухшие, задыхаюсь когда хожу" уходило в кризисный медпротокол и обрывало
# диалог, хотя для коморбидного пациента это рутинный фон, а не острое
# состояние. Острые формулировки без такого маркера (test_acute_medical выше)
# остаются urgent — это исключение не понижает чувствительность в целом.
# --------------------------------------------------------------------------- #

@pytest.mark.parametrize(
    "text",
    [
        "ноги опухшие, задыхаюсь когда хожу, и сахар прыгает",
        "У меня ноги всё время отекают, воздуха не хватает, когда хожу, и сахар скачет",
        "уже несколько дней тяжело дышать при нагрузке, отёки на ногах",
        "последние дни сильная одышка при ходьбе, ничего нового для меня",
        "воздуха не хватает, особенно когда куда-нибудь направляюсь",
        # Без союза "когда"/"при" вообще — перечисление известных симптомов
        # ловится по кластеру отёки+сахар, не по связке с одышкой.
        "У меня ноги всё время отекают, ходить тяжело, сразу задыхаюсь, "
        "да и сахар прыгает то вверх, то вниз.",
        # "распухли" — другой корень, чем "отек"/"опух", отдельный пробел
        "ноги распухли, дышать тяжело стало даже когда просто по квартире "
        "хожу, и сахар всё время то вверх, то вниз",
        # "налились" (отёк) + "как на качелях" (сахар) — ещё два синонима,
        # не покрытых предыдущими двумя раундами фикса
        "ноги опять налились, будто водой, и отдышка замучила, чуть "
        "пройдусь — сразу задыхаюсь, а сахар вообще как на качелях",
    ],
)
def test_chronic_exertional_breathing_stays_concern(text):
    decision = router_l0.classify(text)

    assert decision.safety_level == "concern"
    assert decision.intent is None  # не должно короткого замыкания пайплайна


