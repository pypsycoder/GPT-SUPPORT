"""Кризисные ответы — общие для всех эшелонов защиты.

Их используют два места, и тексты обязаны совпадать:

  * ``BoundaryGuardStage`` — первый эшелон, срабатывает по L0 ДО вызова модели;
  * ``_run_single_agent`` — второй эшелон, перекрывает уже сгенерированный ответ,
    если агент увидел риск там, где L0 промолчал.

Разделение на психологический и медицинский не косметическое. Телефон доверия
при передозировке — вредный совет, а разговор о скорой при суицидальных мыслях
не отвечает на то, что человек сказал.
"""

from __future__ import annotations

# Психологический кризис: человек говорит о смерти или самоповреждении.
CRISIS_RESPONSE = (
    "Слышу, что тебе сейчас очень тяжело. "
    "Я рядом, но в такой момент важно поговорить с живым человеком — "
    "он сможет помочь лучше, чем я.\n\n"
    "Позвони на телефон доверия: 8-800-2000-122 (бесплатно, круглосуточно).\n\n"
    "Если есть кто-то рядом — пожалуйста, скажи ему, что тебе нужна помощь прямо сейчас."
)

# Острое медицинское состояние: платформа не лечит, поэтому единственный
# правильный ответ — отправить к тем, кто лечит, и не рассуждать о чувствах.
MEDICAL_URGENT_RESPONSE = (
    "Это состояние требует помощи врача прямо сейчас, а не разговора со мной.\n\n"
    "Позвони в скорую: 103 (или 112 с мобильного).\n\n"
    "Если рядом есть кто-то — попроси его побыть с тобой и вызвать помощь. "
    "Свой диализный центр тоже предупреди, когда сможешь."
)


def crisis_response(kind: str | None) -> str:
    """Текст под вид кризиса. Неизвестный вид трактуем как психологический."""
    return MEDICAL_URGENT_RESPONSE if kind == "medical" else CRISIS_RESPONSE
