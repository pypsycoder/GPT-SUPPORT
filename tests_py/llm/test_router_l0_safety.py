# --------------------------------------------------------------------------- #
# self_harm + отрицание прямо перед фразой — concern, не urgent. Найдено на
# patient-sim (s04_non_adherent): "чтобы не навредить себе?" (обычный вопрос
# про диету) матчило тот же regex, что реальное "хочу навредить себе".
# Позитивные формы (test_named_method выше, "хочу навредить себе" ниже)
# остаются urgent — отрицание должно стоять прямо перед фразой (окно 2 слова),
# иначе двусмысленное "не хочу, но могу навредить себе" тоже погасло бы.
# --------------------------------------------------------------------------- #

@pytest.mark.parametrize(
    "text",
    [
        "сколько можно есть и пить, чтобы не навредить себе?",
        "я не хочу навредить себе, просто спрашиваю про норму жидкости",
        "как питаться, чтобы не причинить себе вред диетой?",
    ],
)
def test_negated_self_harm_stays_concern(text):
    decision = router_l0.classify(text)

    assert decision.safety_level == "concern"
    assert decision.intent is None


def test_positive_self_harm_intent_still_urgent():
    """Контроль: позитивная форма (без отрицания) не должна погаснуть."""
    assert _urgent("хочу навредить себе")
    assert _urgent("не хочу, но иногда так тяжело, что могу навредить себе")


