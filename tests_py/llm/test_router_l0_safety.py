# Катастрофизация здоровья: триплет смерть-слово + «а вдруг» + мед-контекст.
# Гасит единоличный urgent агента в _apply_agent_safety_net, не трогает L0.
# --------------------------------------------------------------------------- #

@pytest.mark.parametrize(
    "text",
    [
        "А если вдруг шунт забьётся или давление рухнет ночью, кто меня спасёт? "
        "Я так и умру здесь одна.",
        "а что если у меня будет инсульт ночью и никто не поможет, я же умру",
        "а вдруг врачи не успеют и я помру от осложнения прямо на сеансе",
    ],
)
def test_health_catastrophizing_matches(text):
    assert router_l0.looks_like_health_catastrophizing(text)


@pytest.mark.parametrize(
    "text",
    [
        "зачем вообще всё это тянуть, если легче не становится",   # реальный риск
        "было бы проще просто не просыпаться утром",                # реальный риск
        "хочу покончить с собой, серьёзно",                          # реальный риск
        "давление рухнуло совсем, кажется я сейчас умру",           # реальная неотложка (нет «вдруг»)
        "устал от диализа, хочу умереть, больше не могу",           # прямой суицид (нет гипотетики)
        "а вдруг фистула откажет прямо на сеансе, что тогда",       # тревога без смерть-слова
    ],
)
def test_health_catastrophizing_does_not_overmatch(text):
    assert not router_l0.looks_like_health_catastrophizing(text)


