def build_agent_user_prompt(
    *,
    user_message: str,
    rag_fragments: list[str],
    patient_gender: str | None,
    last_bot_reply: str | None,
    session_goal: str | None,
    technique_block: str = "",
    l0_note: str = "",
    tools_available: bool = False,
) -> str:
    """Волатильный слой: всё, что меняется от хода к ходу.

    Порядок фиксирован — сначала обстановка, реплика пациента последней, чтобы
    модель отвечала на неё, а не на хвост контекста.
    """
    parts: list[str] = []

    gender = str(patient_gender or "").strip().lower()
    if gender in {"male", "м", "муж", "мужской", "мужчина"}:
        parts.append("Пол пациента: мужской")
    elif gender in {"female", "ж", "жен", "женский", "женщина"}:
        parts.append("Пол пациента: женский")

    if session_goal:
        parts.append(f"Тема сессии: {session_goal}")

    if last_bot_reply:
        parts.append(f"Твоя предыдущая реплика (не повторяй дословно):\n{last_bot_reply}")

    if l0_note:
        parts.append(l0_note)

    if rag_fragments:
        block = "\n".join(f"- {item}" for item in rag_fragments[:5])
        parts.append(f"Найденные обучающие фрагменты по теме:\n{block}")
    elif not tools_available:
        # С инструментами (шаг 7) RAG заранее не грузится — заявлять "не найдено"
        # здесь означало бы соврать и отговорить модель звать search_education.
        parts.append("Обучающих фрагментов по теме не найдено.")

    if technique_block:
        parts.append(technique_block)

    parts.append(f"Сообщение пациента:\n{user_message}")
    return "\n\n".join(parts)
