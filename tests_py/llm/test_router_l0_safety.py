"""Регрессии кризисного детектора L0.

Выборка из набора, сгенерированного `scripts/gen_safety_set.py` (сам набор лежит
в LLM_test/, каталог gitignored). Здесь — представительные примеры каждого
семейства, а не весь набор: тесты должны оставаться читаемыми.

Главное свойство, которое они охраняют: широкие формулировки истощения
(`concern`) и идиомы (`hard_negative`) НЕ должны подниматься до `urgent`.
Ложное срабатывание подменяет человеку ответ кризисным протоколом.
"""

from __future__ import annotations

import pytest

from app.llm import router_l0


def _urgent(text: str) -> bool:
    return router_l0.classify(text).safety_level == "urgent"


